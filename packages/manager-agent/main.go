var verbose bool
var headlessFlag bool

func main() {
	// ── CLI flags ──
	flag.BoolVar(&verbose, "verbose", false, "Show console output")
	flag.BoolVar(&headlessFlag, "headless", false, "Run without system tray icon")
	flag.Parse()

	// ── Setup log file ──
	logDir := zmmoDir()
	os.MkdirAll(logDir, 0755)
	logPath := filepath.Join(logDir, "system.log")

	f, err := os.OpenFile(logPath, os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0644)
	if err != nil {
		// Fallback: try current directory
		logDir = "."
		os.MkdirAll(filepath.Join(logDir, ".zmmo"), 0755)
		logPath = filepath.Join(logDir, ".zmmo", "system.log")
		f, err = os.OpenFile(logPath, os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0644)
	}
	if err == nil {
		log.SetOutput(f)
		defer f.Close()
	}
	log.SetFlags(log.Ldate | log.Ltime)
	log.Printf("ZMMO Agent v%s starting (pid=%d, %s/%s)...", version, os.Getpid(), runtime.GOOS, runtime.GOARCH)

	// ── Start server ──
	if err := startServer(); err != nil {
		log.Printf("FATAL: %v", err)
		if verbose {
			fmt.Fprintf(os.Stderr, "\n=== ZMMO Agent Error ===\n%v\nLog: %s\nPress Enter...", err, logPath)
			fmt.Scanln()
		}
		os.Exit(1)
	}

	log.Printf("Agent running on port %d", listenPort)

	// ── Headless mode (Linux default, or --headless flag) ──
	if headlessFlag || runtime.GOOS == "linux" {
		log.Printf("Running headless (log: %s)", logPath)
		if verbose {
			fmt.Fprintf(os.Stderr, "\nAgent running on port %d. Log: %s\nCtrl+C to stop.\n", listenPort, logPath)
		}
		select {} // block forever
	}

	// ── Systray mode (Windows / macOS) ──
	runSystray(logPath)
}


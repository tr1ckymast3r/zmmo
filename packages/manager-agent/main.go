// ── Systray ──

func runSystray(logPath string) {
	tray := systray.New()

	menu := systray.NewMenu()

	menu.Add(fmt.Sprintf("Port %d — %s", listenPort, serverStatus()), nil)
	menu.AddSeparator()
	menu.Add("Stop Server", func() { stopServer() })
	menu.Add("Start Server", func() { startServer() })
	menu.Add("Restart Server", func() { restartServer() })
	menu.AddSeparator()
	menu.Add("Open Panel", func() {
		openBrowser(fmt.Sprintf("http://localhost:%d", listenPort))
	})
	menu.AddSeparator()
	menu.Add("Quit", func() {
		stopServer()
		tray.Remove()
		os.Exit(0)
	})

	tray.SetIcon(iconData).
		SetTooltip("ZMMO Device Changer").
		SetMenu(menu)

	tray.OnClick(func() {
		openBrowser(fmt.Sprintf("http://localhost:%d", listenPort))
	})

	tray.Show()

	log.Printf("Systray shown (port %d)", listenPort)
	if err := tray.Run(); err != nil {
		log.Printf("Systray error: %v — falling back to headless", err)
		if verbose {
			fmt.Fprintf(os.Stderr, "Systray unavailable — running headless on port %d\nCtrl+C to stop.\n", listenPort)
		}
		select {} // fallback
	}
}

func openBrowser(url string) {
	var cmd *exec.Cmd
	switch runtime.GOOS {
	case "windows":
		cmd = exec.Command("cmd", "/c", "start", url)
	case "darwin":
		cmd = exec.Command("open", url)
	default:
		cmd = exec.Command("xdg-open", url)
	}
	if cmd != nil {
		cmd.Start()
	}
}

// zmmoDir returns the ZMMO config directory (creates if needed).
// Windows: %APPDATA%\.zmmo  Linux/macOS: ~/.zmmo
func zmmoDir() string {
	dir := os.Getenv("APPDATA")    // Windows: C:\Users\<user>\AppData\Roaming
	if dir == "" {
		dir = os.Getenv("LOCALAPPDATA") // Fallback: AppData\Local
	}
	if dir == "" {
		home, _ := os.UserHomeDir()
		if home == "" {
			home = "."
		}
		dir = filepath.Join(home, ".zmmo")
		return dir
	}
	return filepath.Join(dir, ".zmmo")
}
